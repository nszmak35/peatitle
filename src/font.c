static const Glyph unknown_glyph =
    G(0xFFFD, "#######", "##...##", "##...##", "##...##", "#######");

#define N_GLYPHS (sizeof(glyphs) / sizeof(glyphs[0]))

static const char latin1_fold[] = "AAAAAAACEEEEIIIIDNOOOOOXOUUUUYPS";

static uint32_t normalize(uint32_t cp)
{
    if (cp >= 'a' && cp <= 'z')
        return cp - 32;
    if (cp >= 0x0430 && cp <= 0x044F)
        return cp - 0x20;
    if (cp >= 0x0450 && cp <= 0x045F)
        return cp - 0x50;
    if (cp == 0x0491)
        return 0x0490;
    if (cp >= 0xC0 && cp <= 0xFF) {
        if (cp == 0xF7)
            return '/';
        if (cp == 0xFF)
            return 'Y';
        return (uint32_t)latin1_fold[(cp - 0xC0) & 0x1F];
    }
    if (cp >= 0x2010 && cp <= 0x2015)
        return '-';
    if (cp == 0x2018 || cp == 0x2019 || cp == 0x201A)
        return '\'';
    if (cp == 0x201C || cp == 0x201D || cp == 0x201E)
        return '"';
    return cp;
}

const Glyph *font_lookup(uint32_t cp)
{
    size_t lo = 0, hi = N_GLYPHS;

    cp = normalize(cp);
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (glyphs[mid].cp == cp)
            return &glyphs[mid];
        if (glyphs[mid].cp < cp)
            lo = mid + 1;
        else
            hi = mid;
    }
    return &unknown_glyph;
}

int font_is_space(uint32_t cp)
{
    return cp == ' ' || cp == '\t' || cp == 0xA0;
}
